"""Generate src/palettes.js from GDAL (MIT/X licence, credited in NOTICE).

Writes 256 synthetic lines coloured 0..255 to scratch files, reads them back
through GDAL's OGR DXF and DGN readers and records the RGB each colour index
maps to:
  * ACI  - the standard 256-entry DXF colour index table.
  * DGN  - the default DGN v7 colour table used when a file has no type-5 table.
No drawing files are involved. Run:  python tools/extract_palettes.py
"""
import os
import re
import sys
import tempfile

from osgeo import gdal, ogr

gdal.UseExceptions()
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "palettes.js")


def pen_color(style):
    m = re.search(r"c:#([0-9a-fA-F]{6})", style or "")
    return m.group(1).lower() if m else None


def aci_table(tmp):
    path = os.path.join(tmp, "aci.dxf")
    with open(path, "w") as fh:
        fh.write("0\nSECTION\n2\nENTITIES\n")
        for c in range(1, 256):
            fh.write("0\nLINE\n8\n0\n62\n%d\n10\n%d\n20\n0\n30\n0\n11\n%d\n21\n1\n31\n0\n" % (c, c, c))
        fh.write("0\nENDSEC\n0\nEOF\n")
    ds = ogr.Open(path)
    cols = ["000000"] + [pen_color(f.GetStyleString()) for f in ds.GetLayer(0)]
    cols[7] = "ffffff"  # ACI 7 is "white on dark / black on light"; the renderer swaps it
    assert len(cols) == 256
    return cols


def dgn_table(tmp):
    path = os.path.join(tmp, "pal.dgn")
    ds = ogr.GetDriverByName("DGN").CreateDataSource(path)
    lyr = ds.CreateLayer("e")
    for c in range(256):
        f = ogr.Feature(lyr.GetLayerDefn())
        f.SetGeometry(ogr.CreateGeometryFromWkt("LINESTRING (%d 0, %d 1)" % (c, c)))
        f.SetField("ColorIndex", c)
        lyr.CreateFeature(f)
    ds = None
    ds = ogr.Open(path)
    cols = [pen_color(f.GetStyleString()) for f in ds.GetLayer(0)]
    assert len(cols) == 256
    return cols


def main():
    with tempfile.TemporaryDirectory() as tmp:
        aci = aci_table(tmp)
        dgn = dgn_table(tmp)
    with open(OUT, "w", newline="\n") as fh:
        fh.write("// GENERATED by tools/extract_palettes.py from GDAL (MIT/X licence, see NOTICE). Do not edit.\n")
        fh.write("// Each table is 256 colours as 6-hex-digit RGB strings concatenated.\n")
        fh.write("const ACI_HEX = '%s';\n" % "".join(aci))
        fh.write("const DGN_HEX = '%s';\n" % "".join(dgn))
        fh.write("const unpack = (s) => { const a = new Uint32Array(256); for (let i = 0; i < 256; i++) a[i] = parseInt(s.substr(i * 6, 6), 16); return a; };\n")
        fh.write("/** ACI index -> 0xRRGGBB. Index 7 is white; renderers swap it to black on paper. */\n")
        fh.write("export const ACI = unpack(ACI_HEX);\n")
        fh.write("/** Default DGN v7 colour table (used when the file has no type-5 colour table). */\n")
        fh.write("export const DGN_DEFAULT = unpack(DGN_HEX);\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    sys.exit(main())
