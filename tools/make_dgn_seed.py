"""Embed the leading elements of GDAL's 2D seed design file as src/formats/dgn-seed.js.

    python tools/make_dgn_seed.py

GDAL ships seed_2d.dgn in its data folder (MIT/X licence, see NOTICE). The DGN writer starts
new design files (drawings that were not opened from a DGN) from its first three elements:
the TCB (type 9), the digitizer setup (type 8) and the level symbology (type 10). The writer
then sets the working units, the global origin, a colour table and the elements.
"""
import base64
import os
import struct

from osgeo import gdal

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))


def main():
    data_dir = gdal.GetConfigOption("GDAL_DATA") or os.path.join(os.path.dirname(gdal.__file__), "data", "gdal")
    path = os.path.join(data_dir, "seed_2d.dgn")
    raw = open(path, "rb").read()
    o = 0
    for _ in range(3):
        o += 4 + 2 * struct.unpack("<H", raw[o + 2:o + 4])[0]
    head = raw[:o]
    assert head[1] & 0x7F == 9 and len(head) == 2048, "unexpected seed layout"
    b64 = base64.b64encode(head).decode("ascii")
    lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    js = ("// GENERATED by tools/make_dgn_seed.py from GDAL's seed_2d.dgn (MIT/X licence, see NOTICE).\n"
          "// TCB + digitizer setup + level symbology elements used to start new DGN v7 files. Do not edit.\n"
          "export const SEED_2D = '" + "' +\n  '".join(lines) + "';\n")
    out = os.path.join(ROOT, "src", "formats", "dgn-seed.js")
    with open(out, "w", newline="\n") as fh:
        fh.write(js)
    print("wrote", os.path.relpath(out, ROOT), len(head), "bytes of seed")


if __name__ == "__main__":
    main()
